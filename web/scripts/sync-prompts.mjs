#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(here, "..", "..", "prompts");
const outFile = join(here, "..", "lib", "firewall", "prompts.generated.ts");

function read(name) {
  const content = readFileSync(join(promptsDir, name), "utf8");
  const hash = createHash("sha256").update(content).digest("hex").slice(0, 10);
  return { content, hash };
}

const files = {
  AGENT_GUARDED: "agent-guarded.md",
  AGENT_RAW: "agent-raw.md",
  CHECKER_THREAT: "checker-threat.md",
  CHECKER_INTENT: "checker-intent.md",
  CHECKER_MEMO: "checker-memo.md",
};

const lines = [
  "// AUTO-GENERATED by web/scripts/sync-prompts.mjs — edit prompts/*.md, never this file.",
  "",
];

for (const [key, file] of Object.entries(files)) {
  const { content, hash } = read(file);
  lines.push(`export const ${key} = ${JSON.stringify(content)};`);
  lines.push(`export const ${key}_HASH = ${JSON.stringify(hash)};`);
  lines.push("");
}

const evalSet = read("eval-set.json");
lines.push(`export const EVAL_SET = ${evalSet.content.trim()};`);
lines.push("");
lines.push(`export const EVAL_SET_HASH = ${JSON.stringify(evalSet.hash)};`);
lines.push("");

writeFileSync(outFile, lines.join("\n"));
console.log(`sync-prompts: ${Object.keys(files).length + 1} files → lib/firewall/prompts.generated.ts`);
